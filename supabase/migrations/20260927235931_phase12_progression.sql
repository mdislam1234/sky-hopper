create table public.run_progression (
  user_id uuid not null references auth.users(id) on delete cascade,
  run_id uuid not null,
  perfect_landings integer not null check (perfect_landings between 0 and 10000),
  best_perfect_streak integer not null check (best_perfect_streak between 0 and 10),
  near_misses integer not null check (near_misses between 0 and 10000),
  moving_landings integer not null check (moving_landings between 0 and 10000),
  highest_biome integer not null check (highest_biome between 0 and 4),
  is_daily boolean not null,
  recorded_at timestamptz not null default now(),
  primary key (user_id, run_id),
  foreign key (user_id, run_id) references public.game_scores(user_id, run_id)
);

create table public.daily_challenge_results (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  challenge_date date not null,
  run_id uuid not null,
  game_score_id bigint not null references public.game_scores(id) on delete cascade,
  attempt_number smallint not null check (attempt_number between 1 and 3),
  score integer not null check (score >= 0),
  height integer not null check (height >= 0),
  played_at timestamptz not null default now(),
  unique (user_id, run_id),
  unique (user_id, challenge_date, attempt_number),
  unique (game_score_id)
);

create table public.daily_missions (
  user_id uuid not null references auth.users(id) on delete cascade,
  mission_date date not null,
  mission_id text not null check (mission_id ~ '^[a-z][a-z0-9_]{0,39}$'),
  title text not null,
  description text not null,
  metric text not null,
  target integer not null check (target > 0),
  progress integer not null default 0 check (progress >= 0),
  reward integer not null check (reward between 0 and 100),
  completed_at timestamptz,
  claimed_at timestamptz,
  primary key (user_id, mission_date, mission_id),
  check (claimed_at is null or completed_at is not null)
);

create table public.user_achievements (
  user_id uuid not null references auth.users(id) on delete cascade,
  achievement_id text not null references public.achievement_catalog(id),
  progress integer not null default 0 check (progress >= 0),
  unlocked_at timestamptz,
  claimed_at timestamptz,
  primary key (user_id, achievement_id),
  check (claimed_at is null or unlocked_at is not null)
);

create table public.player_streaks (
  user_id uuid primary key references auth.users(id) on delete cascade,
