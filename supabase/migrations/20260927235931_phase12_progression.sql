create or replace function public.unlock_skin(p_skin_id text)
returns jsonb language plpgsql security definer set search_path = ''
as $$
declare
  v_user uuid := auth.uid();
  v_skin public.skin_catalog%rowtype;
  v_profile public.profiles%rowtype;
  v_unlocked timestamptz;
  v_owned boolean;
begin
  if v_user is null then raise exception 'Authentication required' using errcode = '28000'; end if;
  select * into v_skin from public.skin_catalog where id = p_skin_id and is_active;
  if not found then raise exception 'Skin unavailable' using errcode = '22023'; end if;
  if v_skin.unlock_achievement_id is not null and not exists (
    select 1 from public.user_achievements where user_id = v_user
      and achievement_id = v_skin.unlock_achievement_id and unlocked_at is not null) then
    raise exception 'Achievement required' using errcode = 'SH004';
  end if;
  select * into v_profile from public.profiles where id = v_user for update;
  if not found then raise exception 'Profile unavailable' using errcode = 'P0002'; end if;
  select unlocked_at into v_unlocked from public.user_skins
    where user_id = v_user and skin_id = p_skin_id;
  v_owned := found;
  if not v_owned then
    if v_profile.total_coins < v_skin.cost then raise exception 'Not enough coins' using errcode = 'SH001'; end if;
    update public.profiles set total_coins = total_coins - v_skin.cost
      where id = v_user returning * into v_profile;
    insert into public.user_skins(user_id, skin_id) values (v_user, p_skin_id)
      returning unlocked_at into v_unlocked;
  end if;
  return jsonb_build_object('skin_id', p_skin_id, 'already_owned', v_owned,
    'cost_charged', case when v_owned then 0 else v_skin.cost end,
    'new_total_coins', v_profile.total_coins, 'unlocked_at', v_unlocked,
    'profile_updated_at', v_profile.updated_at);
end;
$$;

